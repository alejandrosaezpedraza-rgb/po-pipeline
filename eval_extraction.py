"""Run the real extraction on the 5 sample POs, compare every field to samples/truth, write EXTRACTION.md.

    python eval_extraction.py               uses PO_EXTRACTOR / PO_MODEL from .env (CLI or API)
    python eval_extraction.py --dry-check   replay mode: checks this script only, prints, writes nothing

Comparison rules (so formatting differences are not counted as misses):
  text      case and whitespace ignored         street   abbreviations normalized (Road = Rd)
  phone     digits only                          numbers  equal within half a cent
  notes     free text: shown, not scored
"""
from __future__ import annotations

import json
import os
import re
import sys
import time
from datetime import datetime

from app import checks, config, extract

ROOT = os.path.dirname(os.path.abspath(__file__))
SLUGS = ["edi-printout", "corporate-form", "store-order", "change-form", "distributor-po"]
NUM = {"qty", "unit_price", "extended", "subtotal", "freight", "tax", "total", "line"}


def norm(key, v):
    if key in NUM:
        try:
            return round(float(v), 2)
        except (TypeError, ValueError):
            return v
    s = re.sub(r"\s+", " ", str(v if v is not None else "")).strip().casefold()
    if key == "phone":
        return re.sub(r"\D", "", s)
    if key == "street":
        return checks.norm_street(s)
    if key == "zip":
        return s.split("-")[0]
    return s.rstrip(".")


def flatten(po):
    out = {}
    for k in ("po_number", "po_date", "requested_ship_date", "payment_terms", "currency",
              "subtotal", "freight", "tax", "total"):
        out[k] = po.get(k)
    for grp, keys in (("buyer", ("company", "contact_name", "email", "phone")),
                      ("bill_to", ("name", "street", "city", "state", "zip")),
                      ("ship_to", ("name", "street", "city", "state", "zip", "store_number"))):
        for k in keys:
            out[f"{grp}.{k}"] = (po.get(grp) or {}).get(k)
    for i, ln in enumerate(po.get("lines") or [], 1):
        for k in ("sku", "customer_item", "description", "qty", "uom", "unit_price", "extended"):
            out[f"lines[{i}].{k}"] = ln.get(k)
    return out


def compare(truth, got):
    t, g = flatten(truth), flatten(got)
    rows = []
    for key in t:
        leaf = key.rsplit(".", 1)[-1]
        ok = norm(leaf, t[key]) == norm(leaf, g.get(key))
        rows.append((key, t[key], g.get(key, "(missing)"), ok))
    for key in g:
        if key not in t:
            rows.append((key, "(no such line)", g[key], False))
    return rows


def main():
    dry = "--dry-check" in sys.argv
    cfg = config.load(overrides={"PO_EXTRACTOR": "replay"} if dry else None)
    info = extract.describe_backend(cfg)
    if not info["ready"]:
        sys.exit(f"Extractor not ready: {info['hint']}")
    if info["kind"] == "replay" and not dry:
        sys.exit("PO_EXTRACTOR=replay is not a real extraction. Use --dry-check, or set PO_EXTRACTOR=auto.")

    results, total_fields, total_ok = [], 0, 0
    for slug in SLUGS:
        with open(os.path.join(ROOT, "samples", "truth", slug + ".json"), encoding="utf-8") as f:
            truth = json.load(f)
        status = []
        t0 = time.time()
        try:
            got = extract.extract(os.path.join(ROOT, "samples", slug + ".pdf"), cfg, status.append)
            err = None
        except extract.ExtractionError as e:
            got, err = {}, str(e)
        secs = time.time() - t0
        rows = compare(truth, got) if not err else []
        ok = sum(r[3] for r in rows)
        n = len(compare(truth, truth))
        total_fields += n
        total_ok += ok
        retried = any("asking again" in s for s in status)
        results.append({"slug": slug, "truth": truth, "got": got, "rows": rows, "ok": ok, "n": n,
                        "err": err, "secs": secs, "retried": retried})
        print(f"{slug:16} {ok}/{n} fields" + (f"  ERROR {err}" if err else "") + f"  ({secs:.1f}s)", flush=True)

    if dry:
        print(f"dry check: {total_ok}/{total_fields}. Nothing written.")
        return

    md = [f"# Extraction results\n",
          f"Run {datetime.now().strftime('%Y-%m-%d %H:%M')} · extractor **{info['label']}** · model `{cfg['PO_MODEL']}`  ",
          f"Generated by `python eval_extraction.py`. Re-run it after changing the prompt, the model or the samples.\n",
          f"**{total_ok} of {total_fields} fields match** across 5 sample POs.\n",
          "Comparison rules: text ignores case and spacing, streets normalize abbreviations (Road = Rd), "
          "phones compare digits, numbers must match to the cent. `notes` is free text and is shown but not scored.\n",
          "| Sample | Layout | Fields matched | Time | Retry needed |", "|---|---|---|---|---|"]
    layouts = {"edi-printout": "EDI 850 translator printout", "corporate-form": "Designed corporate form",
               "store-order": "Store-level order form", "change-form": "PO change notice (revised values)",
               "distributor-po": "Distributor PO, 2 pages"}
    for r in results:
        score = "error" if r["err"] else f"{r['ok']}/{r['n']}"
        md.append(f"| `{r['slug']}` | {layouts[r['slug']]} | {score} | {r['secs']:.0f}s | {'yes' if r['retried'] else 'no'} |")
    for r in results:
        md.append(f"\n## {r['slug']}\n")
        if r["err"]:
            md.append(f"Extraction failed: {r['err']}\n")
            continue
        misses = [x for x in r["rows"] if not x[3]]
        if not misses:
            md.append(f"All {r['n']} fields match.\n")
        else:
            md.append(f"{len(misses)} miss{'es' if len(misses) != 1 else ''}:\n")
            md.append("| Field | Truth | Extracted | Why |")
            md.append("|---|---|---|---|")
            for key, t, g, _ in misses:
                md.append(f"| `{key}` | {json.dumps(t)} | {json.dumps(g)} | _explain_ |")
        md.append(f"\nNotes (not scored): truth “{r['truth'].get('notes', '')}” · extracted “{r['got'].get('notes', '')}”\n")
    with open(os.path.join(ROOT, "EXTRACTION.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(ROOT, "state", "extraction_raw.json"), "w", encoding="utf-8") as f:
        json.dump([{k: r[k] for k in ("slug", "got", "err", "secs")} for r in results], f, indent=1)
    print(f"Wrote EXTRACTION.md: {total_ok}/{total_fields} fields match")


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "state"), exist_ok=True)
    main()
